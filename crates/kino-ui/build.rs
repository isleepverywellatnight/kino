//! KINO's translations for the native interface: the web version's catalogs
//! (web/js/i18n/*.js, a JSON object per language, by key) become a table of
//! texts and a `t!` macro with one arm per key, so an unknown key does not
//! compile. fr.js is the source: its keys are the interface's keys.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

/// The languages, in the table's order (`i18n::Language`).
const LANGUAGES: [&str; 9] = ["fr", "en", "de", "es", "it", "pt", "ru", "ja", "zh"];

fn catalog(path: &PathBuf) -> BTreeMap<String, String> {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let start = text.find("({").expect("a catalog opens with ({") + 1;
    let end = text.rfind("})").expect("a catalog closes with })") + 1;
    serde_json::from_str(&text[start..end]).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../web/js/i18n");
    let catalogs: Vec<BTreeMap<String, String>> = LANGUAGES
        .iter()
        .map(|lang| {
            let path = dir.join(format!("{lang}.js"));
            println!("cargo:rerun-if-changed={}", path.display());
            catalog(&path)
        })
        .collect();
    let keys: Vec<&String> = catalogs[0].keys().collect();

    let mut out = String::new();
    out.push_str("// Generated by build.rs from web/js/i18n/*.js. Do not edit.\n\n");
    writeln!(
        out,
        "#[allow(dead_code)]\npub(crate) const KEYS: usize = {};\n",
        keys.len()
    )
    .unwrap();
    // One row per key, one column per language; None where a language lacks it.
    writeln!(
        out,
        "pub(crate) static TEXTS: [[Option<&str>; {}]; {}] = [",
        LANGUAGES.len(),
        keys.len()
    )
    .unwrap();
    for key in &keys {
        out.push_str("    [");
        for catalog in &catalogs {
            match catalog.get(*key) {
                Some(text) => write!(out, "Some({text:?}), ").unwrap(),
                None => out.push_str("None, "),
            }
        }
        out.push_str("],\n");
    }
    out.push_str("];\n\n");
    // t!("key") -> the text in the current language; t!("key", a, b) fills {}.
    out.push_str("#[macro_export]\nmacro_rules! t {\n");
    for (index, key) in keys.iter().enumerate() {
        writeln!(
            out,
            "    ({key:?}) => {{ $crate::i18n::text({index}) }};\n    ({key:?}, $($arg:expr),+ $(,)?) => {{ $crate::i18n::fill({index}, &[$(&$arg as &dyn ::std::fmt::Display),+]) }};"
        )
        .unwrap();
    }
    out.push_str("}\n");
    let target = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("i18n_table.rs");
    std::fs::write(target, out).unwrap();
}
